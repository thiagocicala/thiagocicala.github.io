const menuButton = document.querySelector(".menu-toggle");
const menu = document.querySelector("#menu-principal");
const languageButtons = document.querySelectorAll("[data-lang]");
const photo = document.querySelector(".hero-photo");

function setMenu(open) {
  menuButton.setAttribute("aria-expanded", String(open));
  menu.classList.toggle("is-open", open);
  document.body.classList.toggle("menu-open", open);
}

menuButton.addEventListener("click", () => setMenu(menuButton.getAttribute("aria-expanded") !== "true"));
menu.querySelectorAll("a").forEach((link) => link.addEventListener("click", () => setMenu(false)));
window.addEventListener("resize", () => {
  if (window.innerWidth > 720) setMenu(false);
});

function setLanguage(lang) {
  const dictionary = translations[lang] || translations.pt;
  document.documentElement.lang = lang === "pt" ? "pt-BR" : lang;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (lang === "pt") {
      if (!element.dataset.original) element.dataset.original = element.innerHTML;
      element.innerHTML = element.dataset.original;
      return;
    }
    if (!element.dataset.original) element.dataset.original = element.innerHTML;
    if (dictionary[key]) element.innerHTML = dictionary[key];
  });

  languageButtons.forEach((button) => button.setAttribute("aria-pressed", String(button.dataset.lang === lang)));
  localStorage.setItem("thiago-site-language", lang);

  const titles = {
    pt: "Thiago Cicala | Zagueiro canhoto Sub-15",
    es: "Thiago Cicala | Defensa central zurdo Sub-15",
    en: "Thiago Cicala | Left-footed U15 centre-back"
  };
  document.title = titles[lang] || titles.pt;
}

languageButtons.forEach((button) => button.addEventListener("click", () => {
  setLanguage(button.dataset.lang);
  setMenu(false);
}));

if (photo) {
  photo.addEventListener("error", () => photo.classList.add("is-unavailable"));
  if (photo.complete && photo.naturalWidth === 0) photo.classList.add("is-unavailable");
}

setLanguage(localStorage.getItem("thiago-site-language") || "pt");
